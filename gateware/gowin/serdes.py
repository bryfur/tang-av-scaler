#!/usr/bin/env python3
"""serdes.py OUT [RATE [REFCLK [WIDTH [GEAR [PLL]]]]]: the transceivers' settings: OUT/serdes.toml and, from it with the
IDE's own converter, OUT/serdes.csr, the register file the place and route takes (avb.tcl).

Quad 0's four lanes as transmitters at RATE ("1.485G": 1080p60's TMDS rate) from REFCLK0
("148.5M": the MS5351M's CLK0/CLK1), WIDTH (10 or 20) bits a word, GEAR ("1:1"; "1:2": the
fabric gives two words at a time at half the word clock), no coding, the lanes' transmit FIFOs
started together by lane 0's (tx_if_cfg_mst_sel: the lanes stay aligned).

PLL: "qpll1" (the default): the quad's LC PLL for all four lanes, so the TMDS clock's lane and the
data lanes move together; "qpll0": the quad's ring PLL; "cpll": each lane's own ring PLL. With
"cpll" the SN65DP159 as a retimer (its PLL on the clock lane, the data through FIFOs) passed
2.97 Gb/s with hundreds of character errors a second on every channel, the sink in and out of lock,
and none as a redriver (measured 2026-11-11, tools/linkq.py): the lanes' PLLs wander apart.

The settings' names and defaults are the IDE's SerDes generator's (serdes-defaults.toml: what
1.9.11 wrote with everything off; the keys 1.9.12's converter added are below). Run in the
fpga-tools container (the converter is the IDE's).
"""
import os
import subprocess
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
CONVERTER = os.path.expanduser(os.environ.get(
    "GW_SERDES_CSR", "~/tools/gowin-standard-1.9.12.04/IDE/bin/serdes_toml_to_csr.dist/serdes_toml_to_csr_138k.bin"))
# 1.9.12's new keys the converter insists on. bias_tc/bias_res only fill the quad's "temp_param"
# register (0x808708 bits 23:20, 19:16), which no file of an earlier release writes at all: its
# lines are left out below, the register stays at its reset value as it did then
NEW_QUAD = {"cmu0_reset_by_fabric": False, "cmu1_reset_by_fabric": False, "bias_tc": 0, "bias_res": 0}
NEW_LANE = {"cpll_reset_by_fabric": False}
DROP = ("temp_param",)


def dump(d, f, prefix=""):
    for k, v in d.items():
        if not isinstance(v, dict):
            f.write("%s = %s\n" % (k, "true" if v is True else "false" if v is False else
                                   '"%s"' % v if isinstance(v, str) else repr(v)))
    for k, v in d.items():
        if isinstance(v, dict):
            f.write("\n\n[%s%s]\n" % (prefix, k))
            dump(v, f, prefix + k + ".")


def main():
    out = os.path.abspath(sys.argv[1])
    rate = sys.argv[2] if len(sys.argv) > 2 else "1.485G"
    ref = sys.argv[3] if len(sys.argv) > 3 else "148.5M"
    width = int(sys.argv[4]) if len(sys.argv) > 4 else 10
    gear = sys.argv[5] if len(sys.argv) > 5 else "1:1"
    pll = {"cpll": 0, "qpll0": 1, "qpll1": 2}[sys.argv[6] if len(sys.argv) > 6 else "qpll1"]
    t = tomllib.load(open(os.path.join(HERE, "serdes-defaults.toml"), "rb"))
    for qn in ("q0", "q1"):
        t[qn].update(NEW_QUAD)
        for n in range(4):
            t[qn]["ln%d" % n].update(NEW_LANE)
    q = t["q0"]
    q["enable"] = True
    q["ref_pad0_freq"] = ref
    for n in range(4):
        q["ln%d" % n].update(enable=True, tx_data_rate=rate, rx_data_rate=rate, width_mode=width,
                             encode_mode="OFF", decode_mode="OFF", tx_gear_rate=gear,
                             tx_if_cfg_mst_sel="q0.ln0", cpll_ref_sel=0, pcs_tx_clk_src=pll)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "serdes.toml"), "w") as f:
        f.write("# generated by gateware/gowin/serdes.py\n")
        dump(t, f)
    raw = os.path.join(out, "serdes-all.csr")
    if os.path.exists(raw):
        os.remove(raw)
    r = subprocess.run([CONVERTER, os.path.join(out, "serdes.toml"), "--comment", "-o", raw],
                       capture_output=True, text=True)
    log = r.stdout + r.stderr
    open(os.path.join(out, "serdes.log"), "w").write(log)
    if not os.path.exists(raw):
        sys.exit("serdes.py: the converter made no file:\n" + log[-2000:])
    lines = [l for l in open(raw) if not any("# q%d.%s" % (k, d) in l for k in (0, 1) for d in DROP)]
    # the place and route's parser takes the plain form: no comments
    open(os.path.join(out, "serdes.csr"), "w").write("".join(l.split("#")[0].rstrip() + "\n" for l in lines))
    plls = [l for l in log.splitlines() if "startup with" in l]
    if not plls:
        sys.exit("serdes.py: no PLL was set up:\n" + log[-2000:])
    print("serdes.py: %d registers; %s" % (len(lines), "; ".join(
        p.split(" startup with: ")[0].split(".", 1)[1] + " " + p.split(" startup with: ")[1].split("(")[0] +
        " VCO " + p.split("fvco=")[1].rstrip(")") + " MHz" for p in plls)))


if __name__ == "__main__":
    main()
