#!/usr/bin/env python3
"""mkgtx.py > rtl/gtx_quad.v: the transceiver quad (GTR12_QUAD, Q0) with its four lanes as plain
transmitters, written from the instance Gowin's IP generator makes (the port list and the tie-offs
of an IDE example: IDE/data/examples/jesd204b_demo/src/serdes/serdes.v). The lanes' settings are
not here: they are the register file the place and route takes (gowin/serdes.py -> serdes.csr).

    ssh fpga 'python3 tools/mkgtx.py' > rtl/gtx_quad.v     (the IDE is installed on fpga)
"""
import os
import re
import sys

EXAMPLE = os.path.expanduser(os.environ.get(
    "GW_SERDES_EXAMPLE", "~/tools/gowin-standard-1.9.12.04/IDE/data/examples/jesd204b_demo/src/serdes/serdes.v"))

# inputs we drive: port pattern -> expression (n = the lane)
INPUTS = [
    (r"FABRIC_LN(\d)_RSTN_I", "ln_rstn[{n}]"),
    (r"FABRIC_LN(\d)_TXDATA_I", "tx_data[{lo} +: 80]"),
    (r"FABRIC_LN(\d)_TX_VLD_IN", "tx_vld[{n}]"),
    (r"LANE(\d)_PCS_TX_RST", "pcs_tx_rst[{n}]"),
    (r"LANE(\d)_FABRIC_TX_CLK", "tx_clk"),
]
# inputs the example drives on its used lanes, off here (no receivers)
OFF = [r"LANE\d_PCS_RX_RST", r"LANE\d_FABRIC_RX_CLK", r"LANE\d_RX_IF_FIFO_RDEN"]
# outputs we take
OUTPUTS = [
    (r"LANE(\d)_PCS_TX_O_FABRIC_CLK", "pcs_tx_clk[{n}]"),
    (r"FABRIC_LANE(\d)_CMU_OK_O", "cmu_ok[{n}]"),
    (r"FABRIC_LANE(\d)_CMU_CK_REF_O", "ref_clk[{n}]"),
    (r"LANE(\d)_TX_IF_FIFO_FULL", "fifo_full[{n}]"),
    (r"LANE(\d)_TX_IF_FIFO_AFULL", "fifo_afull[{n}]"),
    (r"FABRIC_LN(\d)_STAT_O", "stat[{lo13} +: 13]"),
    (r"FABRIC_LN(\d)_ASTAT_O", "astat[{lo6} +: 6]"),
    (r"FABRIC_CMU_OK_O", "qpll_ok[0]"),
    (r"FABRIC_CMU1_OK_O", "qpll_ok[1]"),
]


def main():
    text = open(EXAMPLE).read()
    body = re.search(r"GTR12_QUAD \w+ \((.*?)\n\);", text, re.S).group(1)
    out = []
    for port, expr in re.findall(r"\.(\w+)\((.*?)\)(?:,|$)", body, re.M):
        conn = None
        for pat, fmt in INPUTS + OUTPUTS:
            m = re.fullmatch(pat, port)
            if m:
                n = int(m.group(1)) if m.groups() else 0
                conn = fmt.format(n=n, lo=80 * n, lo13=13 * n, lo6=6 * n)
        if conn is None:
            if any(re.fullmatch(p, port) for p in OFF):
                conn = "1'b0"
            elif "gw_gnd" in expr:              # an input tied off: its width from the example's
                conn = "%d'd0" % expr.count("gw_gnd")
            else:                               # an output not used
                conn = ""
        out.append("        .%s(%s)" % (port, conn))
    print('''// gtx_quad.v: the transceiver quad Q0, its four lanes as plain transmitters.
// GENERATED by tools/mkgtx.py from the instance Gowin's IP generator writes; the lanes' rates,
// PLLs and widths are in the register file the place and route takes (gowin/serdes.py).
//
//   ln_rstn     a lane's reset, active low (FABRIC_LNn_RSTN_I)
//   pcs_tx_rst  its transmit PCS's reset, active high
//   tx_clk      the clock tx_data and tx_vld are given on, every lane (one of pcs_tx_clk)
//   tx_data     a lane's word at [80n +: 80]: its low 10, 20 or 40 bits by the lanes' width (and
//               gearing) in the register file, bit 0 sent first
//   pcs_tx_clk  each lane's word clock; cmu_ok its PLL's lock; ref_clk its reference
//   stat/astat  each lane's status words (13 and 6 bits), qpll_ok the quad's two PLLs

module gtx_quad (
    input  [3:0]  ln_rstn,
    input  [3:0]  pcs_tx_rst,
    input         tx_clk,
    input  [3:0]  tx_vld,
    input  [319:0] tx_data,
    output [3:0]  pcs_tx_clk,
    output [3:0]  cmu_ok,
    output [3:0]  ref_clk,
    output [3:0]  fifo_full,
    output [3:0]  fifo_afull,
    output [51:0] stat,
    output [23:0] astat,
    output [1:0]  qpll_ok
);
    GTR12_QUAD u_quad (
%s
    );
    defparam u_quad.POSITION = "Q0";
endmodule''' % ",\n".join(out))


if __name__ == "__main__":
    main()
